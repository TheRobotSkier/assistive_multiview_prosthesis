def verify_all_dq_tables(f):
    """Run DQ checks across all stored transform arrays."""
    print("\n" + "=" * 60)
    print("DUAL QUATERNION VALIDATION")
    print("=" * 60)

    ok = True
    for key in [
        "index_table",
        "mrl_table",
        "thumb_flex_table",
        "thumb_opp_mode0_table",
        "thumb_opp_mode1_table",
        "palm_table",
    ]:
        ok = verify_dual_quaternion_table(f[key], key) and ok
    return ok


def _dq_translation(dq):
    """Extract translation vector from dual quaternion (via SE3 conversion)."""
    T = _dq_to_se3(dq)
    return T[:3, 3]


def _jump_stats_from_table(table):
    """Compute adjacent-sample jump distances for a table of shape (S, C, 8)."""
    if table.ndim != 3 or table.shape[0] < 2:
        return np.array([], dtype=float)

    samples, contacts, _ = table.shape
    jumps = np.empty((samples - 1) * contacts, dtype=float)
    idx = 0
    for i in range(samples - 1):
        for j in range(contacts):
            p0 = _dq_translation(table[i, j])
            p1 = _dq_translation(table[i + 1, j])
            jumps[idx] = np.linalg.norm(p1 - p0)
            idx += 1
    return jumps


def verify_discretization_jump_lengths(f):
    """Measure positional jump distances between adjacent control samples."""
    print("\n" + "=" * 60)
    print("DISCRETIZATION JUMP LENGTHS")
    print("=" * 60)

    table_keys = [
        "index_table",
        "mrl_table",
        "thumb_flex_table",
        "thumb_opp_mode0_table",
        "thumb_opp_mode1_table",
    ]

    all_jumps = []
    per_table = {}

    zero_tol_m = 1e-9

    for key in table_keys:
        table = f[key]
        jumps = _jump_stats_from_table(table)
        per_table[key] = jumps
        if jumps.size == 0:
            print(f"INFO {key}: no adjacent jumps to evaluate")
            continue

        moving = jumps[jumps > zero_tol_m]
        zero_count = int(jumps.size - moving.size)
        if moving.size > 0:
            all_jumps.append(moving)
            print(
                f"{key}: count={moving.size}, zeros_removed={zero_count}, "
                f"min={moving.min() * 1000.0:.3f} mm, max={moving.max() * 1000.0:.3f} mm, "
                f"median={np.median(moving) * 1000.0:.3f} mm, mean={moving.mean() * 1000.0:.3f} mm"
            )
        else:
            print(f"INFO {key}: all {zero_count} jumps were zero and removed")

    if all_jumps:
        all_concat = np.concatenate(all_jumps)
        print("-" * 60)
        print(
            "overall (non-zero only): "
            f"count={all_concat.size}, "
            f"min={all_concat.min() * 1000.0:.3f} mm, max={all_concat.max() * 1000.0:.3f} mm, "
            f"median={np.median(all_concat) * 1000.0:.3f} mm, mean={all_concat.mean() * 1000.0:.3f} mm"
        )
    else:
        all_concat = np.array([], dtype=float)
        print("INFO No non-zero jump distances were found")

    # Palm table is static by design (no discretization axis), report spread only.
    palm = f["palm_table"]
    palm_pts = np.array([_dq_translation(dq) for dq in palm], dtype=float)
    palm_center = np.mean(palm_pts, axis=0)
    palm_r = np.linalg.norm(palm_pts - palm_center, axis=1)
    print(
        f"palm_table: static points={len(palm_pts)}, "
        f"radius range=[{palm_r.min() * 1000.0:.3f}, {palm_r.max() * 1000.0:.3f}] mm, "
        f"median radius={np.median(palm_r) * 1000.0:.3f} mm, mean radius={palm_r.mean() * 1000.0:.3f} mm"
    )

    return {
        "per_table": per_table,
        "overall": all_concat,
    }


def verify_contact_bbox(f):
    """Compute axis-aligned bbox over all contact points in LUT tables."""
    print("\n" + "=" * 60)
    print("CONTACT POINT BBOX")
    print("=" * 60)

    table_keys = [
        "index_table",
        "mrl_table",
        "thumb_flex_table",
        "thumb_opp_mode0_table",
        "thumb_opp_mode1_table",
        "palm_table",
    ]

    points = []
    for key in table_keys:
        arr = f[key]
        if arr.ndim == 3:
            flat = arr.reshape(-1, 8)
        elif arr.ndim == 2:
            flat = arr
        else:
            continue
        points.extend([_dq_translation(dq) for dq in flat])

    if not points:
        print("INFO no points found for bbox")
        return None

    pts = np.array(points, dtype=float)
    p_min = np.min(pts, axis=0)
    p_max = np.max(pts, axis=0)
    span = p_max - p_min

    print(
        "bbox min [mm]: "
        f"x={p_min[0] * 1000.0:.3f}, y={p_min[1] * 1000.0:.3f}, z={p_min[2] * 1000.0:.3f}"
    )
    print(
        "bbox max [mm]: "
        f"x={p_max[0] * 1000.0:.3f}, y={p_max[1] * 1000.0:.3f}, z={p_max[2] * 1000.0:.3f}"
    )
    print(
        "bbox span [mm]: "
        f"dx={span[0] * 1000.0:.3f}, dy={span[1] * 1000.0:.3f}, dz={span[2] * 1000.0:.3f}"
    )
    print(f"samples used: {len(points)}")

    return {
        "min": p_min,
        "max": p_max,
        "span": span,
        "count": len(points),
    }

def main():
    """Main verification function."""
    print("=" * 60)
    print("FINGER CONTACT LUT VERIFICATION")
    print("=" * 60)
    print(f"LUT Path: {LUT_PATH}")

    if not os.path.exists(LUT_PATH):
        print(f"\nFAIL LUT file not found at {LUT_PATH}")
        return False

    try:
        f = np.load(LUT_PATH, allow_pickle=False)
        print("\nPASS LUT file loaded successfully")

        print_structure(f)

        keys_ok = verify_required_keys(f)
        if not keys_ok:
            f.close()
            return False

        metadata_ok, resolution = verify_metadata(f)
        contact_meta_ok = verify_contact_metadata_consistency(f)
        dims_ok = verify_table_dimensions(f, resolution)
        dq_ok = verify_all_dq_tables(f)
        mode_ok = verify_mode_consistency(f)
        jump_stats = verify_discretization_jump_lengths(f)
        bbox_stats = verify_contact_bbox(f)

        demonstrate_lookup(f)

        f.close()

        all_ok = keys_ok and metadata_ok and contact_meta_ok and dims_ok and dq_ok and mode_ok

        print("\n" + "=" * 60)
        print("VERIFICATION SUMMARY")
        print("=" * 60)
        print(f"required_keys_ok:        {keys_ok}")
        print(f"metadata_ok:             {metadata_ok}")
        print(f"contact_metadata_ok:     {contact_meta_ok}")
        print(f"table_dimensions_ok:     {dims_ok}")
        print(f"dual_quaternion_ok:      {dq_ok}")
        print(f"thumb_mode_consistency:  {mode_ok}")
        print(f"jump_samples_count:      {jump_stats['overall'].size}")
        print(f"bbox_samples_count:      {0 if bbox_stats is None else bbox_stats['count']}")
        print(f"resolution:              {resolution}")
        print(f"\nOverall: {'PASS' if all_ok else 'FAIL'}")
        return all_ok

    except Exception as e:
        print(f"\nFAIL Failed to verify LUT file: {e}")
        import traceback

        traceback.print_exc()
        return False


if __name__ == "__main__":
    success = main()
    exit(0 if success else 1)
